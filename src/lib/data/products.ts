export function productById(id: string | undefined) {
  return products.find((p) => p.id === id);
}

export function productsByStore(storeId: string) {
  return products.filter((p) => p.store_id === storeId);
}

export function featuredProducts() {
  return products.filter((p) => p.featured && p.in_stock);
}

export function trendingProducts() {
  return products.filter((p) => p.trending && p.in_stock);
}

export function saleProducts() {
  return products.filter((p) => !!p.original_price && p.in_stock);
}
